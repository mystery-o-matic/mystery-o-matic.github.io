"""Check bundled emoji images, or render missing ones from the bundled Noto font.

No font installation or network access is needed. Existing colour images are
preserved; additional icons use Noto Emoji's monochrome drawings.
"""

import io
import json
from argparse import ArgumentParser
from pathlib import Path
from zipfile import ZipFile

from emoji import emoji_list
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
IMAGE_DIR = ROOT / "static/images/emoji-data/img-google-64"
ASSET_LIST = ROOT / "static/emoji-assets.js"


def asset_list_source():
    paths = [f"/images/emoji-data/img-google-64/{path.name}" for path in sorted(IMAGE_DIR.glob("*.png"))]
    return "// Generated by scripts/render_emoji_images.py.\nvar EMOJI_IMAGE_ASSETS = " + json.dumps(paths, indent=2) + ";\n"


def required_images():
    source = (ROOT / "static/emoji.js").read_text(encoding="utf8")
    records, _ = json.JSONDecoder().raw_decode(
        source.split("emoji.prototype.data = ", 1)[1]
    )
    aliases = {
        glyph: (key, record[0][0])
        for key, record in records.items()
        for glyph in record[0]
    }
    files = list((ROOT / "mystery_o_matic").rglob("*.py"))
    files += list((ROOT / "static").rglob("*.js"))
    files += list((ROOT / "static").rglob("*.html"))
    result = {}
    for path in files:
        if path.name == "emoji.js":
            continue
        for match in emoji_list(path.read_text(encoding="utf8")):
            glyph = match["emoji"]
            if glyph not in aliases:
                raise ValueError(f"Emoji {glyph!r} in {path} is missing from emoji.js")
            key, canonical = aliases[glyph]
            result[key] = canonical
    return result


def render_missing_images(check=False):
    missing = {
        key: glyph for key, glyph in required_images().items()
        if not (IMAGE_DIR / f"{key}.png").is_file()
    }
    if check:
        if missing:
            raise ValueError("Missing emoji images: " + ", ".join(sorted(missing)))
        if not ASSET_LIST.is_file() or ASSET_LIST.read_text() != asset_list_source():
            raise ValueError("Emoji offline asset list is outdated; run scripts/render_emoji_images.py")
        return 0
    with ZipFile(ROOT / "fonts/Noto_Emoji.zip") as archive:
        font = ImageFont.truetype(
            io.BytesIO(archive.read("static/NotoEmoji-Regular.ttf")), 48
        )
        missing_glyph = bytes(font.getmask("\U0010ffff"))
        for key, glyph in missing.items():
            if any(bytes(font.getmask(char)) == missing_glyph
                   for char in glyph if char not in "\u200d\ufe0e\ufe0f"):
                raise ValueError(f"Bundled Noto font cannot render {glyph!r}")
            image = Image.new("RGBA", (64, 64))
            drawing = ImageDraw.Draw(image)
            left, top, right, bottom = drawing.textbbox((0, 0), glyph, font=font)
            drawing.text(
                ((64 - right - left) / 2, (64 - bottom - top) / 2),
                glyph, font=font, fill="#202020", stroke_width=1, stroke_fill="#ffffff",
            )
            image.save(IMAGE_DIR / f"{key}.png", optimize=True)
        if missing:
            license_text = archive.read("OFL.txt").decode("utf-8")
            license_text = "\n".join(line.rstrip() for line in license_text.splitlines()) + "\n"
            (IMAGE_DIR.parent / "OFL.txt").write_bytes(license_text.encode("utf-8"))
    ASSET_LIST.write_text(asset_list_source(), encoding="utf8")
    return len(missing)


def main():
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if an image is missing")
    args = parser.parse_args()
    try:
        count = render_missing_images(args.check)
    except ValueError as err:
        parser.exit(1, f"{err}\n")
    print("All emoji images are bundled." if args.check else f"Rendered {count} missing emoji images.")


if __name__ == "__main__":
    main()
