"""Shared book layout; case content and map geometry come from the generator."""

from mystery_o_matic.output.latex.utils import create_tex_template, get_emoji_name
from mystery_o_matic.roommap import render_tikz


_LABELS = {
    "en": {
        "snapshot": "Where everyone was at",
        "clues": r"Statements \& clues",
        "murderer": "The murderer",
        "weapon": "The weapon",
        "time": "Time of murder",
    },
    "es": {
        "snapshot": "Dónde estaba cada persona a las",
        "clues": "Declaraciones y pistas",
        "murderer": "El asesino",
        "weapon": "El arma",
        "time": "Hora del asesinato",
    },
}

_CASE_LAYOUT = r"""% Generated by mystery-o-matic; edit the saved JSON and regenerate.
% Uses the host book's styles and macros. The map is generated from the room graph.
\pagestyle{casepage}

\caseintro{$$firstClue}

\begin{sceneband}
\noindent\begin{minipage}[c]{0.77\linewidth}%
\smalllabel{$$snapshot $$finalTime}\par\vspace{0.8ex}
\begingroup
\setlist[itemize]{leftmargin=0.5em,itemsep=0.35ex,topsep=0pt,parsep=0pt}
$$finalLocationsList
\endgroup
\end{minipage}\hfill
\begin{minipage}[c]{0.20\linewidth}%
\centering
\begingroup
\setbox0=\hbox{%
$$roomMap
}%
\ifdim\wd0>\linewidth
  \resizebox{\linewidth}{!}{\usebox0}%
\else
  \usebox0%
\fi
\endgroup
\end{minipage}
\end{sceneband}

\caserule{$$clues}
$$additionalClues

\clearpage
\setcasetableblock
\noindent\begin{minipage}[c][\casetableblock]{\columnwidth}
\vfill
\begin{center}
$$cluesTables

$$weaponsTable

\vfill
\answerlines{$$murderer}{$$weapon}{$$time}
\end{center}
\end{minipage}
\clearpage\pagestyle{plain}
"""


def render_book_case(language, content, locations):
    """Render case content; the host document supplies its opening via caseintro."""
    labels = _LABELS[language]
    fields = {**labels, **content}
    nodes, edges = locations._graph_as_indices()
    fields["roomMap"] = render_tikz(
        [get_emoji_name(locations.representations[node]) for node in nodes],
        edges,
        vertical=locations.name == "train",
    )
    return create_tex_template(_CASE_LAYOUT).substitute(fields)
